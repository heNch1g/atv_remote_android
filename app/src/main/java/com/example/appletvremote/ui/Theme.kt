/**
 * Applies the palette requested in settings.
 *
 * AUTO follows the system, DARK and LIGHT force a mode. On Android 12+ the
 * wallpaper-derived scheme is used in both modes; older devices fall back to
 * the baseline Material 3 palettes.
 */
@Composable
fun AppleTvRemoteTheme(
    themeMode: ThemeMode = ThemeMode.AUTO,
    content: @Composable () -> Unit,
) {
    val dark = when (themeMode) {
        ThemeMode.AUTO -> isSystemInDarkTheme()
        ThemeMode.DARK -> true
        ThemeMode.LIGHT -> false
    }
    val context = LocalContext.current
    val scheme = when {
        Build.VERSION.SDK_INT >= Build.VERSION_CODES.S && dark ->
            dynamicDarkColorScheme(context)

        Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            dynamicLightColorScheme(context)

        dark -> BaselineDark
        else -> BaselineLight
    }
    MaterialTheme(
        colorScheme = scheme,
        content = content,
    )
}
